-- Виды модулей из раздела каталога (ADR-0006, развитие).
-- Вместо ручного списка module_product_ids виды выводятся автоматически из всех товаров
-- под корневым разделом каталога («Новый каталог»). Бизнес кладёт товар в папку —
-- виджет подхватывает. Один конкретный каталог на портал, без переключателя.
-- module_product_ids не дропаем (deprecated, можно убрать на этапе 3).
-- Применяется руками к БД (workflow ADR-0001), затем `npm run updateDB`.

BEGIN;

-- Корневой раздел каталога (iblock 15), из поддерева которого берутся виды модулей.
ALTER TABLE portal ADD COLUMN module_root_section_id integer;

-- Портал 9 (crm.minta24.ru): «Новый каталог» = раздел 37.
UPDATE portal SET module_root_section_id = 37 WHERE id = 9;

COMMIT;
